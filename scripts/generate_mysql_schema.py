"""Generate reviewable MySQL runtime DDL/CI seed from the maintained dev schema.
Static transformation only: this script never opens a database or runs application code.
"""
from pathlib import Path
import re
ROOT=Path(__file__).resolve().parents[1]

def statements(source):
    source=re.sub(r"--[^\n]*", "", source)
    current=[]; quoted=False
    for char in source:
        if char=="'": quoted=not quoted
        if char==';' and not quoted:
            yield ''.join(current).strip();current=[]
        else: current.append(char)
    if ''.join(current).strip():yield ''.join(current).strip()

def convert(sql):
    sql=sql.replace('INSERT OR IGNORE','INSERT IGNORE')
    sql=re.sub(r'\bINTEGER\b','BIGINT',sql)
    sql=sql.replace('PRIMARY KEY AUTOINCREMENT','PRIMARY KEY AUTO_INCREMENT')
    sql=re.sub(r'BIGINT PRIMARY KEY(?! AUTO_INCREMENT)', 'BIGINT PRIMARY KEY AUTO_INCREMENT',sql)
    sql=sql.replace('(unixepoch())','(UNIX_TIMESTAMP())')
    sql=sql.replace('tag_words TEXT','tag_words VARCHAR(191)')
    sql=re.sub(r'\bTEXT\b','LONGTEXT',sql)
    # MySQL requires expression syntax for defaults on TEXT/BLOB columns.
    sql=re.sub(r"(LONGTEXT(?: NOT NULL)? DEFAULT) ('[^']*')",r'\1 (\2)',sql)
    sql=sql.replace('CREATE INDEX IF NOT EXISTS','CREATE INDEX').replace('CREATE UNIQUE INDEX IF NOT EXISTS','CREATE UNIQUE INDEX')
    # SQLite allows explicit row ids (including 0); MySQL AUTO_INCREMENT turns 0
    # into a generated id, which would corrupt seeded rank 0 rows.
    if 'CREATE TABLE IF NOT EXISTS ecs_user_rank' in sql:
        sql=sql.replace('rank_id BIGINT PRIMARY KEY AUTO_INCREMENT','rank_id BIGINT NOT NULL')
    # MySQL CHECK constraints cannot reference an AUTO_INCREMENT column
    # (#3818); this cross-column rule stays enforced by the referral handler.
    sql=sql.replace('CHECK(user_id<>referrer_user_id),','')
    if sql.startswith('CREATE TABLE'):sql+=' ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci'
    return sql

def main():
    ddl=[];seed=[]
    for name in ['001_ecshop_catalog.sql','002_compat.sql','003_checkout.sql','004_rules.sql']:
        for sql in statements((ROOT/'docs/sql/sqlite'/name).read_text(encoding='utf-8-sig')):
            if sql.startswith('INSERT'):seed.append(convert(sql))
            elif sql.startswith('CREATE'):
                if 'WHERE user_id<>0' in sql:continue
                ddl.append(convert(sql))
    ddl.extend([
        "ALTER TABLE ecs_users ADD COLUMN mobile_phone VARCHAR(32) NOT NULL DEFAULT '', ADD COLUMN is_validated BIGINT NOT NULL DEFAULT 0, ADD COLUMN pay_points BIGINT NOT NULL DEFAULT 0",
        "ALTER TABLE ecs_tag ADD COLUMN authenticated_user_id BIGINT GENERATED ALWAYS AS (NULLIF(user_id,0)) STORED",
        "CREATE UNIQUE INDEX uk_tag_member ON ecs_tag(authenticated_user_id,goods_id,tag_words)",
    ])
    out=ROOT/'docs/sql/mysql';out.mkdir(exist_ok=True)
    header='-- Generated by scripts/generate_mysql_schema.py; review and commit with dev schema changes.\n'
    (out/'001_runtime.sql').write_text(header+'SET FOREIGN_KEY_CHECKS=0;\n'+';\n'.join(ddl)+';\nSET FOREIGN_KEY_CHECKS=1;\n',encoding='utf-8')
    (out/'ci_seed.sql').write_text('-- CI/development fixtures only; do not import as production data.\n'+';\n'.join(seed)+';\n',encoding='utf-8')
    print(f'Generated {len(ddl)} DDL statements and {len(seed)} CI fixture statements')
if __name__=='__main__':main()
